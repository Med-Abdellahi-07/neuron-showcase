/**
 * حماية الخصوصية قبل أي إرسال إلى مزوّد خارجي (الخطة المجانية لـ Gemini تُستعمل لتحسين منتجات Google).
 * 1) لا نُرسل أبداً بيانات الملف الشخصي (الاسم، البريد، الهاتف، المعرّف): الشيفرة لا تمررها أصلاً.
 * 2) ما يكتبه الطالب بنفسه يُنقّى من الأنماط الواضحة للبريد والهاتف والروابط الشخصية قبل الإرسال.
 */
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;
// هاتف: 8 أرقام فأكثر (مع فواصل/مسافات/+)، ويستثني الأعداد العشرية القصيرة والمعادلات
const PHONE = /(?<![\w.])\+?\d[\d\s().-]{6,}\d(?![\w])/g;

export function scrubPII(text: string): string {
  return text
    .replace(EMAIL, "[email]")
    .replace(PHONE, (m) => (m.replace(/\D/g, "").length >= 8 ? "[phone]" : m));
}
